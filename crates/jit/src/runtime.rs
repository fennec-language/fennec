//! Running compiled code: the one place its entry point is called, and the failures native
//! checks report. Everything else native code calls is in `fennec_interp::embed`.

use fennec_interp::embed::{self, Tables};
use fennec_syntax::{Diagnostic, Module};

pub(crate) use fennec_interp::embed::checks::{
    DIVISION_BY_ZERO, NEGATIVE_SQRT, NOT_AN_INT, OVERFLOW, TOO_DEEP, ZERO_STEP,
};

/// A compiled program's entry point.
pub(crate) struct Entry {
    pub(crate) code: *const u8,
    // Keeps the machine code alive while it runs.
    pub(crate) _module: cranelift_jit::JITModule,
}

pub(crate) struct Outcome {
    pub(crate) output: Vec<u8>,
    pub(crate) failure: Option<Diagnostic>,
    pub(crate) leftovers: embed::Leftovers,
}

/// Sets up the runtime as a run does, and takes it down again without running anything.
pub(crate) fn start_only(module: &Module, tables: Tables) -> Result<(), Diagnostic> {
    embed::start(module, tables, fennec_interp::Inputs::default())?;
    embed::finish();
    Ok(())
}

/// A compiled test's name, how it failed if it did, and the program functions it ran, unless
/// some of them ran in the interpreter, which doesn't keep count.
pub(crate) type TestRun = (String, Option<Diagnostic>, Option<Vec<String>>);

/// The functions whose flags are set, clearing them for the next test.
fn take_flags(flags: &[(String, *mut u8)]) -> Vec<String> {
    let mut ran = Vec::new();
    for (key, flag) in flags {
        #[expect(
            unsafe_code,
            reason = "each flag is a byte of writable data that the running module owns, and compiled \
                      code that writes it runs only on this thread, between these reads"
        )]
        let set = unsafe {
            let set = flag.read_volatile() != 0;
            flag.write_volatile(0);
            set
        };
        if set {
            ran.push(key.clone());
        }
    }
    ran
}

/// Runs a compiled benchmark on this thread, or only starts the runtime with `execute` false:
/// how long it took, and how it failed if it did.
pub(crate) fn run_bench(
    tests: &crate::lower::CompiledTests,
    module: &Module,
    tables: Tables,
    execute: bool,
) -> Result<Option<(std::time::Duration, Option<Diagnostic>)>, Diagnostic> {
    embed::start(module, tables, fennec_interp::Inputs::default())?;
    let timed = tests.entries.first().filter(|_| execute).map(|(_, code)| {
        #[expect(
            unsafe_code,
            reason = "the code was just generated by Cranelift for `fn()` with no arguments or results"
        )]
        let bench = unsafe { std::mem::transmute::<*const u8, extern "C" fn()>(*code) };
        let started = std::time::Instant::now();
        bench();
        let took = started.elapsed();
        (took, embed::next_test())
    });
    embed::finish();
    Ok(timed)
}

/// Runs compiled tests one after another on this thread.
pub(crate) fn run_tests(
    tests: &crate::lower::CompiledTests,
    module: &Module,
    tables: Tables,
) -> Result<Vec<TestRun>, Diagnostic> {
    embed::start(module, tables, fennec_interp::Inputs::default())?;
    let mut results = Vec::with_capacity(tests.entries.len());
    for (name, code) in &tests.entries {
        #[expect(
            unsafe_code,
            reason = "the code was just generated by Cranelift for `fn()` with no arguments or results"
        )]
        let test = unsafe { std::mem::transmute::<*const u8, extern "C" fn()>(*code) };
        test();
        let ran = take_flags(&tests.flags);
        let traced = (!embed::ran_in_interpreter()).then_some(ran);
        results.push((name.clone(), embed::next_test(), traced));
    }
    embed::finish();
    Ok(results)
}

pub(crate) fn execute(
    entry: &Entry,
    module: &Module,
    tables: Tables,
    inputs: fennec_interp::Inputs,
) -> Result<Outcome, Diagnostic> {
    embed::start(module, tables, inputs)?;
    #[expect(
        unsafe_code,
        reason = "the code was just generated by Cranelift for `fn()` with no arguments or results"
    )]
    let main = unsafe { std::mem::transmute::<*const u8, extern "C" fn()>(entry.code) };
    main();
    let (output, failure, leftovers) = embed::finish();
    Ok(Outcome { output, failure, leftovers })
}
