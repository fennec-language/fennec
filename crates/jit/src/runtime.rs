//! Running compiled code: the one place its entry point is called, and the failures native
//! checks report. Everything else native code calls is in `fennec_interp::embed`.

use fennec_interp::embed::{self, Tables};
use fennec_syntax::{Diagnostic, Module};

pub(crate) use fennec_interp::embed::checks::{
    DIVISION_BY_ZERO, NEGATIVE_SQRT, NOT_AN_INT, OVERFLOW, TOO_DEEP, ZERO_STEP,
};

/// A compiled program's entry point.
pub(crate) struct Entry {
    pub(crate) code: *const u8,
    // Keeps the machine code alive while it runs.
    pub(crate) _module: cranelift_jit::JITModule,
}

pub(crate) struct Outcome {
    pub(crate) output: Vec<u8>,
    pub(crate) failure: Option<Diagnostic>,
    pub(crate) leftovers: embed::Leftovers,
}

/// Runs compiled tests one after another on this thread, each with how it failed, if it did.
pub(crate) fn run_tests(
    tests: &crate::lower::CompiledTests,
    module: &Module,
    tables: Tables,
) -> Result<Vec<(String, Option<Diagnostic>)>, Diagnostic> {
    embed::start(module, tables, fennec_interp::Inputs::default())?;
    let mut results = Vec::with_capacity(tests.entries.len());
    for (name, code) in &tests.entries {
        #[expect(
            unsafe_code,
            reason = "the code was just generated by Cranelift for `fn()` with no arguments or results"
        )]
        let test = unsafe { std::mem::transmute::<*const u8, extern "C" fn()>(*code) };
        test();
        results.push((name.clone(), embed::next_test()));
    }
    embed::finish();
    Ok(results)
}

pub(crate) fn execute(
    entry: &Entry,
    module: &Module,
    tables: Tables,
    inputs: fennec_interp::Inputs,
) -> Result<Outcome, Diagnostic> {
    embed::start(module, tables, inputs)?;
    #[expect(
        unsafe_code,
        reason = "the code was just generated by Cranelift for `fn()` with no arguments or results"
    )]
    let main = unsafe { std::mem::transmute::<*const u8, extern "C" fn()>(entry.code) };
    main();
    let (output, failure, leftovers) = embed::finish();
    Ok(Outcome { output, failure, leftovers })
}
