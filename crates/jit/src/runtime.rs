//! What compiled code calls back into: printing, failures, and the one place the compiled
//! entry point is called. Output and string literals live in thread-locals, so compiled code
//! passes only plain numbers and no pointers are dereferenced here.

use std::cell::{Cell, RefCell};

use fennec_syntax::{Diagnostic, Span};

pub(crate) const OVERFLOW: i64 = 1;
pub(crate) const DIVISION_BY_ZERO: i64 = 2;
pub(crate) const ZERO_STEP: i64 = 3;

thread_local! {
    /// Set when the program fails; compiled code checks it after every call and returns
    /// early. Per thread, so programs running on different threads can't see each other's.
    static FAILED: Cell<u8> = const { Cell::new(0) };
    static FAIL_SPAN: Cell<Span> = const { Cell::new(Span { start: 0, end: 0 }) };
    static OUTPUT: RefCell<String> = const { RefCell::new(String::new()) };
    static STRINGS: RefCell<Vec<String>> = const { RefCell::new(Vec::new()) };
}

/// A compiled program's entry point, and the string literals it prints.
pub(crate) struct Entry {
    pub(crate) code: *const u8,
    pub(crate) strings: Vec<String>,
    // Keeps the machine code alive while it runs.
    pub(crate) _module: cranelift_jit::JITModule,
}

pub(crate) struct Outcome {
    pub(crate) output: String,
    pub(crate) failure: Option<Diagnostic>,
}

/// Where this thread's failure flag lives, for compiled code to read. Code compiled here must
/// also run here, which `crate::run` guarantees by doing both in one call.
pub(crate) fn failed_flag() -> usize {
    FAILED.with(|flag| flag.as_ptr().addr())
}

pub(crate) fn execute(entry: &Entry) -> Outcome {
    FAILED.set(0);
    OUTPUT.with_borrow_mut(String::clear);
    STRINGS.with_borrow_mut(|strings| strings.clone_from(&entry.strings));
    #[expect(
        unsafe_code,
        reason = "the code was just generated by Cranelift for `fn()` with no arguments or results"
    )]
    let main = unsafe { std::mem::transmute::<*const u8, extern "C" fn()>(entry.code) };
    main();
    let output = OUTPUT.with_borrow_mut(std::mem::take);
    let failure = match i64::from(FAILED.get()) {
        0 => None,
        code => Some(failure(code)),
    };
    Outcome { output, failure }
}

fn failure(code: i64) -> Diagnostic {
    let span = FAIL_SPAN.get();
    match code {
        OVERFLOW => Diagnostic::new("this calculation overflows an int", span)
            .with_help("ints are 64-bit; check the values involved, or use floats for very large numbers"),
        DIVISION_BY_ZERO => Diagnostic::new("division by zero", span),
        _ => Diagnostic::new("`range` can't step by 0", span),
    }
}

pub(crate) extern "C" fn fail(code: i64, start: i64, end: i64) {
    FAIL_SPAN.set(Span { start: u32::try_from(start).unwrap_or(0), end: u32::try_from(end).unwrap_or(0) });
    FAILED.set(u8::try_from(code).unwrap_or(1));
}

fn write(text: &str) {
    OUTPUT.with_borrow_mut(|output| output.push_str(text));
}

pub(crate) extern "C" fn print_int(value: i64) {
    write(&value.to_string());
}

pub(crate) extern "C" fn print_float(value: f64) {
    write(&fennec_interp::format_float(value));
}

pub(crate) extern "C" fn print_bool(value: i8) {
    write(if value != 0 { "True" } else { "False" });
}

pub(crate) extern "C" fn print_str(index: i64) {
    STRINGS.with_borrow(|strings| {
        if let Some(text) = usize::try_from(index).ok().and_then(|at| strings.get(at)) {
            write(text);
        }
    });
}
